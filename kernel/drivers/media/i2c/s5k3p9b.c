static int __s5k3p9b_start_stream(struct s5k3p9b *s5k3p9b)
{
	int ret;

	ret = s5k3p9b_write_array(s5k3p9b->client, s5k3p9b->cur_mode->reg_list);
	if (ret)
		return ret;

	/* In case these controls are set before streaming */
	mutex_unlock(&s5k3p9b->mutex);
	ret = v4l2_ctrl_handler_setup(&s5k3p9b->ctrl_handler);
	mutex_lock(&s5k3p9b->mutex);
	if (ret)
		return ret;

	s5k3p9b_write_reg(s5k3p9b->client,
				 S5K3P9B_REG_STREAM_ON0,
				 S5K3P9B_REG_VALUE_16BIT, 0x4000);
	s5k3p9b_write_reg(s5k3p9b->client,
				 S5K3P9B_REG_STREAM_ON1,
				 S5K3P9B_REG_VALUE_16BIT, 0x0100);
	s5k3p9b_write_reg(s5k3p9b->client,
				 S5K3P9B_REG_STREAM_ON2,
				 S5K3P9B_REG_VALUE_16BIT, 0x0100);
	return 0;
}

static int __s5k3p9b_stop_stream(struct s5k3p9b *s5k3p9b)
{
	return s5k3p9b_write_reg(s5k3p9b->client,
				 S5K3P9B_REG_CTRL_MODE,
				 S5K3P9B_REG_VALUE_16BIT,
				 S5K3P9B_MODE_SW_STANDBY);
}

static int s5k3p9b_s_stream(struct v4l2_subdev *sd, int on)
{
	struct s5k3p9b *s5k3p9b = to_s5k3p9b(sd);
	struct i2c_client *client = s5k3p9b->client;
	int ret = 0;

	dev_info(&client->dev, "%s: on: %d, %dx%d@%d\n", __func__, on,
				s5k3p9b->cur_mode->width,
				s5k3p9b->cur_mode->height,
		DIV_ROUND_CLOSEST(s5k3p9b->cur_mode->max_fps.denominator,
				  s5k3p9b->cur_mode->max_fps.numerator));

	mutex_lock(&s5k3p9b->mutex);
	on = !!on;
	if (on == s5k3p9b->streaming)
		goto unlock_and_return;

	if (on) {
		ret = pm_runtime_get_sync(&client->dev);
		if (ret < 0) {
			pm_runtime_put_noidle(&client->dev);
			goto unlock_and_return;
		}

		ret = __s5k3p9b_start_stream(s5k3p9b);
		if (ret) {
			v4l2_err(sd, "start stream failed while write regs\n");
			pm_runtime_put(&client->dev);
			goto unlock_and_return;
		}
	} else {
		__s5k3p9b_stop_stream(s5k3p9b);
		pm_runtime_put(&client->dev);
	}

	s5k3p9b->streaming = on;

unlock_and_return:
	mutex_unlock(&s5k3p9b->mutex);

	return ret;
}

static int s5k3p9b_s_power(struct v4l2_subdev *sd, int on)
{
	struct s5k3p9b *s5k3p9b = to_s5k3p9b(sd);
	struct i2c_client *client = s5k3p9b->client;
	int ret = 0;

	mutex_lock(&s5k3p9b->mutex);

	/* If the power state is not modified - no work to do. */
	if (s5k3p9b->power_on == !!on)
		goto unlock_and_return;

	if (on) {
		ret = pm_runtime_get_sync(&client->dev);
		if (ret < 0) {
			pm_runtime_put_noidle(&client->dev);
			goto unlock_and_return;
		}

		s5k3p9b->power_on = true;
	} else {
		pm_runtime_put(&client->dev);
		s5k3p9b->power_on = false;
	}

unlock_and_return:
	mutex_unlock(&s5k3p9b->mutex);

	return ret;
}

/* Calculate the delay in us by clock rate and clock cycles */
static inline u32 s5k3p9b_cal_delay(u32 cycles)
{
	return DIV_ROUND_UP(cycles, S5K3P9B_XVCLK_FREQ / 1000 / 1000);
}

static int __s5k3p9b_power_on(struct s5k3p9b *s5k3p9b)
{
	int ret;
	u32 delay_us;
	struct device *dev = &s5k3p9b->client->dev;

	usleep_range(1000, 2000);

	if (!IS_ERR_OR_NULL(s5k3p9b->pins_default)) {
		ret = pinctrl_select_state(s5k3p9b->pinctrl,
					   s5k3p9b->pins_default);
		if (ret < 0)
			dev_err(dev, "could not set pins\n");
	}
	ret = clk_set_rate(s5k3p9b->xvclk, S5K3P9B_XVCLK_FREQ);
	if (ret < 0)
		dev_warn(dev, "Failed to set xvclk rate (24MHz)\n");
	if (clk_get_rate(s5k3p9b->xvclk) != S5K3P9B_XVCLK_FREQ)
		dev_warn(dev, "xvclk mismatched, modes are based on 24MHz\n");
	ret = clk_prepare_enable(s5k3p9b->xvclk);
	if (ret < 0) {
		dev_err(dev, "Failed to enable xvclk\n");
		return ret;
	}
	if (!IS_ERR(s5k3p9b->reset_gpio))
		gpiod_set_value_cansleep(s5k3p9b->reset_gpio, 0);

	ret = regulator_bulk_enable(S5K3P9B_NUM_SUPPLIES, s5k3p9b->supplies);
	if (ret < 0) {
		dev_err(dev, "Failed to enable regulators\n");
		goto disable_clk;
	}

	ret = regulator_enable(s5k3p9b->iovdd_regulator);
	if (ret < 0) {
		dev_err(dev, "Failed to enable iovdd regulator\n");
		goto disable_iovdd;
	}
	
	ret = regulator_enable(s5k3p9b->avdd_regulator);
	if (ret < 0) {
		dev_err(dev, "Failed to enable AVDD regulator\n");
		goto disable_avdd;
	}
   
    ret = regulator_enable(s5k3p9b->dvdd_regulator);
	if (ret < 0) {
		dev_err(dev, "Failed to enable DVDD regulator\n");
		goto disable_dvdd;
	}

	if (!IS_ERR(s5k3p9b->reset_gpio))
		gpiod_set_value_cansleep(s5k3p9b->reset_gpio, 1);

	usleep_range(500, 1000);
	if (!IS_ERR(s5k3p9b->pwdn_gpio))
		gpiod_set_value_cansleep(s5k3p9b->pwdn_gpio, 1);

	/* 8192 cycles prior to first SCCB transaction */
	delay_us = s5k3p9b_cal_delay(8192);
	usleep_range(delay_us, delay_us * 2);

	return 0;

disable_dvdd:
	regulator_disable(s5k3p9b->dvdd_regulator);
disable_iovdd:
	regulator_disable(s5k3p9b->iovdd_regulator);
disable_avdd:
	regulator_disable(s5k3p9b->avdd_regulator);
disable_clk:
	clk_disable_unprepare(s5k3p9b->xvclk);
	return ret;

}

static void __s5k3p9b_power_off(struct s5k3p9b *s5k3p9b)
{
	int ret;
	struct device *dev = &s5k3p9b->client->dev;

	regulator_disable(s5k3p9b->iovdd_regulator);
	regulator_disable(s5k3p9b->avdd_regulator);
	regulator_disable(s5k3p9b->dvdd_regulator);
    usleep_range(1*1000, 2 * 1000);

	if (!IS_ERR(s5k3p9b->pwdn_gpio))
		gpiod_set_value_cansleep(s5k3p9b->pwdn_gpio, 0);
	clk_disable_unprepare(s5k3p9b->xvclk);
	if (!IS_ERR(s5k3p9b->reset_gpio))
		gpiod_set_value_cansleep(s5k3p9b->reset_gpio, 0);

	if (!IS_ERR_OR_NULL(s5k3p9b->pins_sleep)) {
		ret = pinctrl_select_state(s5k3p9b->pinctrl,
					   s5k3p9b->pins_sleep);
		if (ret < 0)
			dev_dbg(dev, "could not set pins\n");
	}

	regulator_bulk_disable(S5K3P9B_NUM_SUPPLIES, s5k3p9b->supplies);

}

static int s5k3p9b_runtime_resume(struct device *dev)
{

	struct i2c_client *client = to_i2c_client(dev);
	struct v4l2_subdev *sd = i2c_get_clientdata(client);
	struct s5k3p9b *s5k3p9b = to_s5k3p9b(sd);
	__s5k3p9b_power_on(s5k3p9b);

	return 0;
}

static int s5k3p9b_runtime_suspend(struct device *dev)
{

	struct i2c_client *client = to_i2c_client(dev);
	struct v4l2_subdev *sd = i2c_get_clientdata(client);
	struct s5k3p9b *s5k3p9b = to_s5k3p9b(sd);
	__s5k3p9b_power_off(s5k3p9b);

	return 0;
}

