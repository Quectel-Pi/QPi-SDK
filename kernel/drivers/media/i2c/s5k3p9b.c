static int s5k3p9b_enum_frame_interval(struct v4l2_subdev *sd,
                  struct v4l2_subdev_state *sd_state,
				       struct v4l2_subdev_frame_interval_enum *fie)
{
	if (fie->index >= ARRAY_SIZE(supported_modes))
		return -EINVAL;

	if (fie->code != S5K3P9B_MEDIA_BUS_FMT)
		return -EINVAL;

	fie->width = supported_modes[fie->index].width;
	fie->height = supported_modes[fie->index].height;
	fie->interval = supported_modes[fie->index].max_fps;

	return 0;
}

static int s5k3p9b_g_mbus_config(struct v4l2_subdev *sd, unsigned int pad,
				struct v4l2_mbus_config *config)
{
	config->type = V4L2_MBUS_CSI2_DPHY;
	config->bus.mipi_csi2.num_data_lanes = S5K3P9B_LANES;

	return 0;
}

#define CROP_START(SRC, DST) (((SRC) - (DST)) / 2 / 4 * 4)
#define DST_WIDTH_2096 2096
#define DST_HEIGHT_1560 1560

static int s5k3p9b_get_selection(struct v4l2_subdev *sd,
				struct v4l2_subdev_state *sd_state,
				struct v4l2_subdev_selection *sel)
{
	struct s5k3p9b *s5k3p9b = to_s5k3p9b(sd);

	if (sel->target == V4L2_SEL_TGT_CROP_BOUNDS) {
		if (s5k3p9b->cur_mode->width == 2104) {
			sel->r.left = CROP_START(s5k3p9b->cur_mode->width, DST_WIDTH_2096);
			sel->r.width = DST_WIDTH_2096;
			sel->r.top = CROP_START(s5k3p9b->cur_mode->height, DST_HEIGHT_1560);
			sel->r.height = DST_HEIGHT_1560;
		} else {
			sel->r.left = CROP_START(s5k3p9b->cur_mode->width,
							s5k3p9b->cur_mode->width);
			sel->r.width = s5k3p9b->cur_mode->width;
			sel->r.top = CROP_START(s5k3p9b->cur_mode->height,
							s5k3p9b->cur_mode->height);
			sel->r.height = s5k3p9b->cur_mode->height;
		}
		return 0;
	}

	return -EINVAL;
}

