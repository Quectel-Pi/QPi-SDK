static int s5k3p9b_open(struct v4l2_subdev *sd, struct v4l2_subdev_fh *fh)
{
   printk("s5k3p9b_open\n");
	struct s5k3p9b *s5k3p9b = to_s5k3p9b(sd);
	struct v4l2_mbus_framefmt *try_fmt =
				v4l2_subdev_get_try_format(sd, fh->state, 0);
	const struct s5k3p9b_mode *def_mode = &supported_modes[0];

	mutex_lock(&s5k3p9b->mutex);
	/* Initialize try_fmt */
	try_fmt->width = def_mode->width;
	try_fmt->height = def_mode->height;
	try_fmt->code = S5K3P9B_MEDIA_BUS_FMT;
	try_fmt->field = V4L2_FIELD_NONE;

	mutex_unlock(&s5k3p9b->mutex);
	/* No crop or compose */

	return 0;
}
