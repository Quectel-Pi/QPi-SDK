static long s5k3p9b_ioctl(struct v4l2_subdev *sd, unsigned int cmd, void *arg)
{
	struct s5k3p9b *s5k3p9b = to_s5k3p9b(sd);
	long ret = 0;
	u32 stream = 0;

	switch (cmd) {
	case RKMODULE_GET_MODULE_INFO:
		s5k3p9b_get_module_inf(s5k3p9b, (struct rkmodule_inf *)arg);
		break;
	case RKMODULE_SET_QUICK_STREAM:

		stream = *((u32 *)arg);

		if (stream){
			ret = s5k3p9b_write_reg(s5k3p9b->client,
				 0x6028, S5K3P9B_REG_VALUE_16BIT, 0x4000);
			ret = s5k3p9b_write_reg(s5k3p9b->client,
				 0x602A, S5K3P9B_REG_VALUE_16BIT, 0x0100);
			ret = s5k3p9b_write_reg(s5k3p9b->client,
				 0x6F12, S5K3P9B_REG_VALUE_16BIT, 0x0100);
		} else{
			ret = s5k3p9b_write_reg(s5k3p9b->client,
				 S5K3P9B_REG_CTRL_MODE,
				 S5K3P9B_REG_VALUE_16BIT,
				 S5K3P9B_MODE_SW_STANDBY);
		}
		break;
	default:
		ret = -ENOIOCTLCMD;
		break;
	}

	return ret;
}

